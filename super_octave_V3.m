    patch('Parent', ax, 'XData', shX, 'YData', shY, ...
          'FaceColor', [0.15 0.1 0.05], 'EdgeColor', 'none');      % shadows = depth effect
    iGround = (S(:,5) == 1);
    iBlock  = (S(:,5) == 2);
    iStone  = (S(:,5) == 3);
    [gX, gY] = rects_xy(S(iGround, 1:4));
    patch('Parent', ax, 'XData', gX, 'YData', gY, ...
          'FaceColor', [0.55 0.35 0.15], 'EdgeColor', 'k');        % ground
    nG = sum(iGround);
    [grX, grY] = rects_xy([S(iGround, 1), -0.8 * ones(nG, 1), S(iGround, 3), zeros(nG, 1)]);
    patch('Parent', ax, 'XData', grX, 'YData', grY, ...
          'FaceColor', [0.2 0.7 0.2], 'EdgeColor', 'none');        % grass
    if any(iBlock)
      [bX, bY] = rects_xy(S(iBlock, 1:4));
      patch('Parent', ax, 'XData', bX, 'YData', bY, ...
            'FaceColor', [0.6 0.6 0.65], 'EdgeColor', 'k');        % blocks
    endif
    if any(iStone)
      [stX, stY] = rects_xy(S(iStone, 1:4));
      patch('Parent', ax, 'XData', stX, 'YData', stY, ...
            'FaceColor', [0.55 0.65 0.85], 'EdgeColor', 'k', 'LineWidth', 1.2);  % floating stones
      nS = sum(iStone);
      [tpX, tpY] = rects_xy([S(iStone, 1), S(iStone, 4) - 0.4, S(iStone, 3), S(iStone, 4)]);
      patch('Parent', ax, 'XData', tpX, 'YData', tpY, ...
            'FaceColor', [0.85 0.92 1.0], 'EdgeColor', 'none');    % light top of the stones
    endif

    if nSpikes > 0                              % spikes: all triangles in one patch
      spX = zeros(3, 0);
      spY = zeros(3, 0);
      for k = 1:nSpikes
        nTri = max(2, round((spikes(k,2) - spikes(k,1)) / 1.4));
        triW = (spikes(k,2) - spikes(k,1)) / nTri;
        for i = 1:nTri
          xs = spikes(k,1) + (i - 1) * triW;
          spX(:, end+1) = [xs; xs + triW / 2; xs + triW];
          spY(:, end+1) = [0; 2.2; 0];
        endfor
      endfor
      patch('Parent', ax, 'XData', spX, 'YData', spY, ...
            'FaceColor', [0.78 0.78 0.85], 'EdgeColor', 'k');
    endif

    hPlat = zeros(1, nPlat);                    % handles of moving platforms
    for k = 1:nPlat
      hPlat(k) = rectangle('Parent', ax, 'Position', [platX(k) - platW(k)/2, platTop(k) - 1.2, platW(k), 1.2], ...
                           'FaceColor', [0.95 0.60 0.10], 'EdgeColor', 'k', 'LineWidth', 1.2);
    endfor

    rectangle('Parent', ax, 'Position', [goalX, 0, 0.8, 14], 'FaceColor', [0.9 0.9 0.9]);  % flag pole
    hFlag = patch('Parent', ax, 'XData', [goalX + 0.8, goalX + 7, goalX + 0.8], ...
                  'YData', [14, 11.5, 9], 'FaceColor', [1 0.1 0.1]);  % red flag = closed

    hBook = zeros(1, nBooks);                   % handles of books
    for k = 1:nBooks
      bookCol = bookColors(mod(k, 3) + 1, :);                      % cover color
      hBook(k) = patch('Parent', ax, 'Faces', bookF, ...
                       'Vertices', bookV + repmat(books(k, :), 16, 1), ...
                       'FaceVertexCData', [bookCol; bookCol * 0.55; 1 1 0.85; 1 1 1], ...
                       'FaceColor', 'flat', 'EdgeColor', 'k', 'LineWidth', 0.5);
    endfor

    hCoffee = 0;                                % handle of the coffee cup
    if coffeeAlive
      hCoffee = patch('Parent', ax, 'Faces', coffeeF, ...
                      'Vertices', coffeeV + repmat(coffee, 12, 1), ...
                      'FaceVertexCData', [1 1 1; 0.35 0.18 0.05; 0.9 0.9 0.9], ...
                      'FaceColor', 'flat', 'EdgeColor', 'k', 'LineWidth', 0.5);
    endif

    virSX  = cell(1, nViruses);                 % virus outlines
    virSY  = cell(1, nViruses);
    hVirus = zeros(1, nViruses);                % handles of virus bodies
    hEyes  = zeros(1, nViruses);                % handles of virus eyes
    eyeDx  = 0.17 * virW;                       % horizontal eye offset
    eyeDy  = 0.57 * virH;                       % eye height
    for k = 1:nViruses
      vt = virType(k);
      [virSX{k}, virSY{k}] = virus_shape(vt, virW(k), virH(k));
      hVirus(k) = patch('Parent', ax, 'XData', virX(k) + virSX{k}, 'YData', virYnow(k) + virSY{k}, ...
                        'FaceColor', typeBody(vt, :), 'EdgeColor', typeEdge(vt, :), 'LineWidth', 1.2);
      hEyes(k)  = line('Parent', ax, 'XData', virX(k) + eyeDx(k) * [-1 1], ...
                       'YData', virYnow(k) + eyeDy(k) * [1 1], 'LineStyle', 'none', ...
                       'Marker', 'o', 'MarkerSize', 4 + 4 * (vt == 3), ...
                       'MarkerFaceColor', typeEye(vt, :), 'MarkerEdgeColor', 'k');   % two eyes
    endfor

    hPlayer  = patch('Parent', ax, 'XData', 5 + brainX, 'YData', brainY, ...
                     'FaceColor', [1 0.65 0.75], 'EdgeColor', [0.6 0.1 0.3], ...
                     'LineWidth', 1.5);                  % pink brain body
    hDetails = line('Parent', ax, 'XData', [5 + foldX, NaN, 5.5 + 0.5 * mouthT], ...
                    'YData', [foldY, NaN, 1.2 + 0.35 * mouthT.^2], ...
                    'Color', [0.6 0.1 0.3], 'LineWidth', 1.5);   % central fold + smile
    hEyesP   = line('Parent', ax, 'XData', [4.5 5.5], 'YData', [2.3 2.3], 'LineStyle', 'none', ...
                    'Marker', 'o', 'MarkerSize', 4, ...
                    'MarkerFaceColor', 'w', 'MarkerEdgeColor', [0.3 0.1 0.2]);   % eye whites
    hPupils  = line('Parent', ax, 'XData', [4.6 5.6], 'YData', [2.3 2.3], 'LineStyle', 'none', ...
                    'Marker', 'o', 'MarkerSize', 2, ...
                    'MarkerFaceColor', 'k', 'MarkerEdgeColor', 'k');             % black pupils

    hHearts = patch('Parent', ax, 'XData', 2.5 + heartRelX(:, 1:lives), 'YData', heartAllY(:, 1:lives), ...
                    'FaceColor', [0.90 0.10 0.20], 'EdgeColor', [0.45 0 0.1], 'LineWidth', 1);  % lives
    hInfo = text(ax, 0, 0, '', 'Color', 'w', 'FontSize', 12, ...
                 'BackgroundColor', [0.1 0.1 0.1], 'VerticalAlignment', 'top');
    set(hInfo, 'Units', 'normalized');          % fixed on the screen (no update when the camera moves)
    set(hInfo, 'Position', [0.015 0.91 0]);
    hMsg  = text(ax, 0, 0, '', 'Color', 'w', 'FontSize', 14, 'FontWeight', 'bold', ...
                 'HorizontalAlignment', 'center', 'BackgroundColor', [0.1 0.1 0.1]);  % messages
    set(hMsg, 'Units', 'normalized');
    set(hMsg, 'Position', [0.5 0.38 0]);
    hPop  = text(ax, 0, 0, '', 'Color', 'w', 'FontSize', 14, 'FontWeight', 'bold', ...
                 'HorizontalAlignment', 'center');       % floating score (+10, +100)

    % ---- Reset the player for this level ------------------------------------
    px = 5; py = 0; vy = 0;                     % position and vertical speed
    onGround    = false;
    ridePlat    = 0;                            % index of the platform carrying the player (0 = none)
    faceDir     = 1;                            % direction the brain looks at (+1 right / -1 left)
    invuln      = 0;                            % invulnerability frames after a hit
    starMode    = 0;                            % coffee invincibility frames
    flagWasOpen = false;
    wasPaused   = false;
    pausedTime  = 0;                            % time spent in pause (not counted in the time bonus)
    camX        = 0;                            % camera position
    popFrames   = 0; popX = 0; popY = 0;        % floating score state
    msgFrames   = 0;                            % message display time
    status      = 'playing';
    drawPx = NaN; drawPy = NaN; drawFace = 0;   % last drawn player state
    visDrawn = true; goldDrawn = false;         % last drawn player look
    camDrawn = -1; livesDrawn = lives;          % last drawn camera and hearts
    hudDrawn = '';                              % last drawn HUD text
    setappdata(fig, 'jumpRequested', false);
    setappdata(fig, 'keys', [false false]);     % avoid a key stuck from the previous level
    setappdata(fig, 'paused', false);
    levelTimer = tic();                         % level timer (time bonus)
    lastTic    = tic();                         % frame timer (steady speed)

    % ---- Main loop of one level ---------------------------------------------
    while strcmp(status, 'playing') && ishandle(fig)

      % Pause (P key)
      if getappdata(fig, 'paused')
        set(hMsg, 'String', 'PAUSED - press P to resume');
        wasPaused  = true;
        pausedTime = pausedTime + 0.1;
        drawnow();
        pause(0.1);
        continue;
      elseif wasPaused
        set(hMsg, 'String', '');
        wasPaused = false;
        lastTic   = tic();
      endif

      % Time step: if the computer is slow, movements are scaled so the speed stays constant
      dt      = min(max(toc(lastTic) / framePause, 0.5), 2.5);
      lastTic = tic();
      t       = t + dt;
      died    = false;

      % Moving platforms: new positions
      platXold = platX;
      platX    = P(:, 2)' + P(:, 5)' .* sin(P(:, 7)' * t + P(:, 8)');
      platTop  = P(:, 3)' + P(:, 6)' .* sin(P(:, 7)' * t + P(:, 8)');

      % Carry the player if he stands on a platform
      if ridePlat > 0
        px = px + platX(ridePlat) - platXold(ridePlat);
        py = platTop(ridePlat);
      endif

      % Input: run with the left/right arrows
      keys = getappdata(fig, 'keys');           % [left right]
      vx   = maxSpeed * (keys(2) - keys(1));    % +speed right, -speed left, 0 if none or both
      if vx ~= 0
        faceDir = sign(vx);                     % brain looks where it runs
      endif

      % Input: jump (only if standing on something)
      if getappdata(fig, 'jumpRequested')
        if onGround
          vy = jumpSpeed;
          onGround = false;
        endif
        setappdata(fig, 'jumpRequested', false);
      endif

      % Horizontal movement and collisions with solids
      pxNew = px + vx * dt;
      hitX  = find(pxNew + playerW/2 > S(:,1) & pxNew - playerW/2 < S(:,3) & ...
                   py + playerH > S(:,2) & py < S(:,4) - 1e-6);
      for k = hitX(:)'
        if vx > 0
          pxNew = S(k,1) - playerW/2;           % stopped by the left side of the solid
        elseif vx < 0
          pxNew = S(k,3) + playerW/2;           % stopped by the right side of the solid
        endif
      endfor
      px = max(pxNew, playerW/2);               % left wall of the world

      % Vertical movement (gravity) and landing on ground, blocks, stones or platforms
      vy       = vy - gravity * dt;
      pyNew    = py + vy * dt;
      onGround = false;
      ridePlat = 0;
      if vy < 0
        landTop  = -Inf;
        landPlat = 0;
        land = find(px + playerW/2 > S(:,1) & px - playerW/2 < S(:,3) & ...
                    py >= S(:,4) - 1e-6 & pyNew < S(:,4));
        if ~isempty(land)
          landTop = max(S(land, 4));            % highest solid under the player
        endif
        plHit = find(px + playerW/2 > platX - platW/2 & px - playerW/2 < platX + platW/2 & ...
                     py >= platTop - 0.05 & pyNew <= platTop);
        if ~isempty(plHit)
          [topBest, iBest] = max(platTop(plHit));
          if topBest > landTop
            landTop  = topBest;                 % a moving platform is higher than the solid
            landPlat = plHit(iBest);
          endif
        endif
        if landTop > -Inf
          pyNew    = landTop;
          onGround = true;
          vy       = 0;
          ridePlat = landPlat;                  % 0 if landing on a solid
        endif
      elseif vy > 0
        bump = find(px + playerW/2 > S(:,1) & px - playerW/2 < S(:,3) & ...
                    py + playerH <= S(:,2) + 1e-6 & pyNew + playerH > S(:,2));
        if ~isempty(bump)
          pyNew = min(S(bump, 2)) - playerH;    % head hits a solid
          vy = 0;
        endif
      endif
      py = pyNew;

      % Timers
      invuln   = max(invuln - dt, 0);
      starMode = max(starMode - dt, 0);
      virInv   = max(virInv - dt, 0);

      % Viruses: move (the boss gets faster when hurt)
      virX = virX + virDir .* virSpeed .* (1 + 0.5 * (virMaxHP - virHP)) * dt;
      turn = virX > virMax | virX < virMin;
      virDir(turn) = -virDir(turn);
      virX = min(max(virX, virMin), virMax);
      virYnow = virY0 + virBob .* sin(0.08 * t + virPh);   % flying viruses go up and down

      % Viruses: collision with the player
      virHit = find(virAlive & abs(px - virX) < (playerW + virW)/2 & ...
                    py < virYnow + virH & py + playerH > virYnow);
      for k = virHit(:)'
        stompable = (virType(k) == 1 || virType(k) == 3);
        fromAbove = (vy < 0 && py > virYnow(k) + virH(k) * 0.4);
        if virInv(k) > 0
          % boss is recovering: harmless
        elseif (stompable && fromAbove) || starMode > 0
          virHP(k) = virHP(k) - 1;              % one hit
          if fromAbove
            vy = 0.6 * jumpSpeed;               % small bounce
          endif
          if virHP(k) <= 0
            virAlive(k) = false;                % virus destroyed
            set([hVirus(k) hEyes(k)], 'Visible', 'off');
            totalScore = totalScore + virPts(virType(k));
            set(hPop, 'String', sprintf('+%d', virPts(virType(k))));
          else
            virInv(k) = 45;                     % boss flashes after a hit
            totalScore = totalScore + 50;
            set(hPop, 'String', 'HIT! +50');
          endif
          popFrames = 30; popX = px; popY = py + playerH + 1;
        elseif invuln == 0
          died = true;                          % touched from the side, or not stompable
        endif
      endfor
      bossLeft = any(virAlive & virType == 3);

      % Spikes
      if nSpikes > 0 && invuln == 0 && starMode == 0 && py < 1.8
        if any(px + 1 > spikes(:,1) & px - 1 < spikes(:,2))
          died = true;
        endif
      endif

      % Books (small pick-up zone: the player must be precise)
      bookHit = find(bookAlive & abs(books(:,1)' - px) < 2.2 & abs(books(:,2)' - (py + playerH/2)) < 3);
      for k = bookHit(:)'
        bookAlive(k) = false;
        set(hBook(k), 'Visible', 'off');
        booksCollected = booksCollected + 1;
        gameBooksGot   = gameBooksGot + 1;
        totalScore     = totalScore + 10;
        popFrames = 30; popX = px; popY = py + playerH + 1;
        set(hPop, 'String', '+10');
        if booksCollected == booksNeeded && bossLeft
          msgFrames = 90;
          set(hMsg, 'String', 'Enough books! Now defeat the boss!');
        endif
      endfor

      % Coffee: invincibility
      if coffeeAlive && abs(coffee(1) - px) < 2.5 && abs(coffee(2) - (py + playerH/2)) < 3.5
        coffeeAlive = false;
        set(hCoffee, 'Visible', 'off');
        starMode  = coffeeTime;
        msgFrames = 60;
        set(hMsg, 'String', 'COFFEE! You are invincible!');
      endif

      % Flag opens when enough books are collected (and the boss is dead)
      flagOpen = (booksCollected >= booksNeeded) && ~bossLeft;
      if flagOpen && ~flagWasOpen
        flagWasOpen = true;
        set(hFlag, 'FaceColor', [0.1 0.8 0.2]);   % flag turns green
        msgFrames = 90;
        set(hMsg, 'String', 'The flag is open! Run!');
      endif

      % Falling in a hole
      if py < -25
        died = true;
      endif

      % Death: lose a heart and go back to the last checkpoint
      if died
        lives    = lives - 1;
        ridePlat = 0;
        if lives == 0
          status = 'lost';
        else
          px = max(segStarts(segStarts <= px)) + 2;   % start of the last ground piece
          py = 0; vy = 0;
          invuln = 60;
        endif
      endif

      % Flag reached
      if px >= goalX
        if flagOpen
          status = 'won';
        else
          px = goalX - 1;                       % pushed back
          msgFrames = 60;
          if booksCollected < booksNeeded
            set(hMsg, 'String', sprintf('Not enough books! %d / %d', booksCollected, booksNeeded));
          else
            set(hMsg, 'String', 'Defeat the boss first!');
          endif
        endif
      endif

      % Camera (background, hearts and view are updated only when the camera moved)
      camX = min(max(px - 30, 0), worldLength - 100);
      if camX ~= camDrawn
        set(ax, 'XLim', [camX camX + 100]);
        cloudXs = camX + mod(cloudBase - 0.5 * camX + 20, 140) - 20;   % clouds: slow parallax
        set(hClouds, 'XData', cloudRelX + ones(cloudN, 1) * cloudXs);
        hillXs  = camX + mod(hillBase - 0.7 * camX + 30, 160) - 30;    % hills: medium parallax
        set(hHills, 'XData', hillRelX + ones(hillN, 1) * hillXs);
      endif

      % Hearts (one heart disappears when a life is lost)
      if camX ~= camDrawn || lives ~= livesDrawn
        if lives >= 1
          set(hHearts, 'XData', camX + 2.5 + heartRelX(:, 1:lives), 'YData', heartAllY(:, 1:lives));
        else
          set(hHearts, 'XData', NaN(30, 1), 'YData', NaN(30, 1));
        endif
        livesDrawn = lives;
      endif
      camDrawn = camX;

      % Graphics: moving platforms
      for k = 1:nPlat
        set(hPlat(k), 'Position', [platX(k) - platW(k)/2, platTop(k) - 1.2, platW(k), 1.2]);
      endfor

      % Graphics: player (redrawn only if something changed)
      if px ~= drawPx || py ~= drawPy || faceDir ~= drawFace
        set(hPlayer,  'XData', px + brainX, 'YData', py + brainY);        % move the brain
        set(hDetails, 'XData', [px + foldX, NaN, px + faceDir * 0.5 + 0.5 * mouthT], ...
                      'YData', [py + foldY, NaN, py + 1.2 + 0.35 * mouthT.^2]);  % fold + smile
        eyeX = px + faceDir * 0.5 + [-0.5 0.5];                           % eyes shift in the run direction
        eyeY = (py + 2.3) * [1 1];
        set(hEyesP,  'XData', eyeX, 'YData', eyeY);
        set(hPupils, 'XData', eyeX + faceDir * 0.12, 'YData', eyeY - 0.05);  % pupils look ahead
        drawPx = px; drawPy = py; drawFace = faceDir;
      endif
      goldNow = (starMode > 0 && mod(floor(t / 3), 2) == 0);
      if goldNow ~= goldDrawn
        if goldNow
          set(hPlayer, 'FaceColor', [1 0.9 0.2]);                         % golden flash = invincible
        else
          set(hPlayer, 'FaceColor', [1 0.65 0.75]);
        endif
        goldDrawn = goldNow;
      endif
      visNow = ~(invuln > 0 && mod(floor(invuln / 5), 2) == 0);           % blinking when hurt
      if visNow ~= visDrawn
        if visNow
          set([hPlayer hDetails hEyesP hPupils], 'Visible', 'on');
        else
          set([hPlayer hDetails hEyesP hPupils], 'Visible', 'off');
        endif
        visDrawn = visNow;
      endif

      % Graphics: viruses (only those near the screen)
      inView = find(virAlive & virX > camX - 15 & virX < camX + 115);
      for k = inView(:)'
        set(hVirus(k), 'XData', virX(k) + virSX{k}, 'YData', virYnow(k) + virSY{k});
        set(hEyes(k),  'XData', virX(k) + virDir(k) * 0.2 + eyeDx(k) * [-1 1], ...
                       'YData', virYnow(k) + eyeDy(k) * [1 1]);
        if virInv(k) > 0
          if mod(floor(virInv(k) / 4), 2) == 0
            visState = 'off';                   % boss blinks when hurt
          else
            visState = 'on';
          endif
          set([hVirus(k) hEyes(k)], 'Visible', visState);
          virBlink(k) = true;
        elseif virBlink(k)
          set([hVirus(k) hEyes(k)], 'Visible', 'on');
          virBlink(k) = false;
        endif
      endfor

      % Graphics: floating score and messages
      if popFrames > 0
        popFrames = popFrames - dt;
        popY = popY + 0.3 * dt;                 % floating score goes up
        set(hPop, 'Position', [popX popY 0]);
        if popFrames <= 0
          set(hPop, 'String', '');
        endif
      endif
      if msgFrames > 0
        msgFrames = msgFrames - dt;
        if msgFrames <= 0
          set(hMsg, 'String', '');
        endif
      endif

      % Graphics: HUD text (updated only when the text changes)
      hud = sprintf('Level %d/%d   Score: %d   Books: %d/%d (need %d)', ...
                    level, nLevels, totalScore, booksCollected, nBooks, booksNeeded);
      if starMode > 0
        hud = [hud sprintf('   COFFEE: %d s', ceil(starMode * framePause))];
      endif
      bossIdx = find(virType == 3 & virAlive);
      if ~isempty(bossIdx)
        hud = [hud sprintf('   BOSS HP: %d', virHP(bossIdx(1)))];
      endif
      if ~strcmp(hud, hudDrawn)
        set(hInfo, 'String', hud);
        hudDrawn = hud;
      endif

      drawnow();
      rest = framePause - toc(lastTic);         % wait only the time left in the frame
      if rest > 0.001
        pause(rest);
      endif
    endwhile

    if ~ishandle(fig)                           % figure closed by the player: stop
      break;
    endif

    % ---- End of the level ---------------------------------------------------
    if strcmp(status, 'won')
      timeBonus  = round(max(0, 500 - 5 * (toc(levelTimer) - pausedTime)));  % faster = more points
      totalScore = totalScore + 200 * level + timeBonus;      % level bonus + time bonus
      lifeLine = '';
      if (level == 2 || level == 4) && lives < maxLives
        lives    = lives + 1;                   % reward after levels 2 and 4
        lifeLine = '+1 heart!';
      endif
      if level < nLevels
        show_screen(ax, {'LEVEL COMPLETE!', '', ...
                         sprintf('Level bonus: %d   Time bonus: %d', 200 * level, timeBonus), ...
                         sprintf('Score: %d', totalScore), lifeLine, '', ...
                         sprintf('Next: %s', levelNames{level + 1})});
        pause(3);
      endif
      level = level + 1;                        % next level (harder)
    endif
  endwhile

  if ~ishandle(fig)
    break;
  endif

  % ---- End of the game ------------------------------------------------------
  if lives > 0 && level > nLevels
    outcome = 'YOU WIN - You graduated!';
  else
    outcome = 'GAME OVER';
  endif
  if totalScore > bestScore
    bestScore = totalScore;                     % new record
  endif

  fid = fopen('results.txt', 'a');              % save the result (append mode)
  fprintf(fid, '%s ; level %d ; score %d ; books %d/%d ; lives %d ; %s\n', ...
          datestr(now, 'yyyy-mm-dd HH:MM:SS'), min(level, nLevels), totalScore, ...
          gameBooksGot, gameBooksAll, lives, outcome);
  fclose(fid);

  show_screen(ax, {outcome, '', sprintf('Score: %d   Best score: %d', totalScore, bestScore), ...
                   sprintf('Books collected: %d / %d', gameBooksGot, gameBooksAll), ...
                   '', 'Press R to replay or Q to quit'});
  key = wait_for_key(fig, {'r', 'q'});          % replay or stop
  keepPlaying = strcmp(key, 'r');
endwhile

if ishandle(fig)
  close(fig);
endif
disp('Thanks for playing!');
