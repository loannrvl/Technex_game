% ---- Function: build a level (harder when level increases) -------------
function [S, P, spikes, books, coffee, viruses, segStarts, goalX, worldLength] = build_level(level, runSeed, nLevels)
  rand('state', runSeed * 10 + level);          % same level during a run, new levels at each replay
  nSegTab = [5 6 7 8 8];                        % number of ground pieces per level
  gapMin  = [6 10 14 18 22];                    % minimum hole width per level
  gapRnd  = [3 4 4 5 5];                        % random part of the hole width
  platSpd = [0.030 0.035 0.045 0.055 0.065];    % moving platform speed per level
  pMove   = [0 0.35 0.30 0.30 0.25];            % chance that a hole gets a moving platform
  pSpike  = [0 0.7 0.7 0.8 0.9];            % chance of spikes on a ground piece
  pEnemy  = [0.55 0.55 0.55 0.60 0.65];         % chance of a virus on a ground piece
  pAir    = [0.80 0.70 0.60 0.50 0.40];         % chance of floating platforms on a safe piece
  nSeg    = nSegTab(level) + (level == nLevels);% last level: extra piece = boss arena
  S         = zeros(0, 5);                      % solids: [x1 y1 x2 y2 kind] (1 ground, 2 block, 3 stone)
  P         = zeros(0, 8);                      % moving platforms: [type cx cy w ampX ampY speed phase]
  spikes    = zeros(0, 2);                      % spikes: [x1 x2]
  cand      = zeros(0, 2);                      % candidate positions for books and coffee
  viruses   = zeros(0, 6);                      % viruses: [xmin xmax speed type y0 bob]
  segStarts = zeros(1, nSeg);                   % start of each ground piece (checkpoints)
  x = 0;
  for s = 1:nSeg
    isArena = (level == nLevels) && (s == nSeg);
    if s == 1
      segLen = 45;                              % safe first piece
    elseif isArena
      segLen = 80;                              % big arena for the boss
    else
      segLen = 38 - 3 * level + 10 * rand();    % ground pieces get shorter
    endif
    segStarts(s) = x;
    S(end+1, :) = [x, -10, x + segLen, 0, 1];   % ground piece
    if isArena
      viruses(end+1, :) = [x + 10, x + segLen - 16, 0.45, 3, 0, 0];  % the boss
      S(end+1, :) = [x + 18, 7.5, x + 27, 8.7, 3];   % stones to escape from the boss
      S(end+1, :) = [x + 48, 7.5, x + 57, 8.7, 3];
      cand(end+1, :) = [x + 22.5, 10.9];
      cand(end+1, :) = [x + 52.5, 10.9];
    else
      hasBlock  = false;
      hasHazard = false;
      hasFly    = false;
      if level >= 2 && s > 1 && rand() < min(0.25 + 0.1 * level, 0.7)
        bx = x + segLen * (0.3 + 0.3 * rand());
        bw = 5 + 2 * (level >= 4);
        bh = min(2.5 + 2 * rand() + (level - 1), 8);  % blocks get taller
        S(end+1, :) = [bx, 0, bx + bw, bh, 2];  % block to jump over
        cand(end+1, :) = [bx + bw / 2, bh + 3 + rand()];  % book above the block
        hasBlock = true;
      endif
           if s > 1
        vMin = x + 4;                           % walking zone of the viruses: whole piece...
        vMax = x + segLen - 4;
        if hasBlock                             % ...or the biggest side of the block
          if (bx - 2) - (x + 4) > (x + segLen - 4) - (bx + bw + 2)
            vMax = bx - 2;                      % viruses walk before the block
          else
            vMin = bx + bw + 2;                 % viruses walk after the block
          endif
        endif
        sw        = 4 + 0.5 * level;            % width of one spike group
        wantSpike = ~hasBlock && rand() < pSpike(level);  % spikes: independent roll
        wantVirus = rand() < pEnemy(level);               % viruses: independent roll
        if wantSpike && wantVirus               % both: spikes at the end, viruses before them
          sx = x + 0.55 * segLen;
          spikes(end+1, :) = [sx, sx + sw];
          vMax = sx - 2;
        elseif wantSpike
          if level >= 4 && segLen > 28 && rand() < 0.5
            spikes(end+1, :) = [x + 0.22 * segLen, x + 0.22 * segLen + sw];  % two groups
            spikes(end+1, :) = [x + 0.60 * segLen, x + 0.60 * segLen + sw];
          else
            sx = x + segLen * (0.3 + 0.35 * rand());
            spikes(end+1, :) = [sx, sx + sw];
          endif
        endif
        hasHazard = wantSpike;
        if wantVirus && (vMax - vMin) >= 6      % enough room to patrol
          nv = 1 + (level >= 4 && rand() < 0.5);% two viruses on some pieces from level 4
          for i = 1:nv
            if level >= 3 && rand() < 0.15 * (level - 2)
              vt = 2;                           % red virus (cannot be stomped)
            else
              vt = 1;                           % green virus
            endif
            viruses(end+1, :) = [vMin, vMax, 0.14 + 0.08 * level, vt, 0, 0];
          endfor
          hasHazard = true;
        endif
        if level >= 4 && rand() < 0.25 * (level - 3) + 0.1
          viruses(end+1, :) = [x + 3, x + segLen - 3, 0.11 + 0.06 * level, 4, 6.5, 1.5];  % flying virus
          hasFly = true;
        endif
      endif
      safeSeg = ~hasBlock && ~hasHazard && ~hasFly;
      if s == 1 || (safeSeg && rand() < pAir(level))
        fw = max(5, 9 - level);                 % floating platforms get narrower
        fx = x + segLen * (0.15 + 0.20 * rand());
        fy = 6 + 2 * rand();                    % height of the underside
        S(end+1, :) = [fx, fy, fx + fw, fy + 1.2, 3];
        topX = fx + fw / 2;
        topY = fy + 1.2;
        if segLen > 28 && level >= 2 && rand() < 0.6
          fx2 = fx + fw + 3;                    % second, higher stone (small staircase)
          fy2 = fy + 2;
          S(end+1, :) = [fx2, fy2, fx2 + fw, fy2 + 1.2, 3];
          topX = fx2 + fw / 2;
          topY = fy2 + 1.2;
        endif
        cand(end+1, :) = [topX, topY + 2.2];    % book standing on the platform
      elseif ~hasBlock
        cand(end+1, :) = [x + segLen * (0.2 + 0.6 * rand()), 7 + 4 * rand()];
      endif
    endif
    if s < nSeg
      gap = gapMin(level) + gapRnd(level) * rand();  % holes get wider
      gx  = x + segLen;
      cx  = gx + gap / 2;
      if level >= 2 && rand() < pMove(level)    % moving platform (only some holes)
        if level >= 3 && gap <= 18 && rand() < 0.4
          P(end+1, :) = [2, cx, 3.5, 7, 0, 3.5, platSpd(level), 2 * pi * rand()];  % vertical
          cand(end+1, :) = [cx, 10 + 2 * rand()];
        else
          P(end+1, :) = [1, cx, 0, 7, gap / 2 - 3.8, 0, platSpd(level), 2 * pi * rand()];  % horizontal
          cand(end+1, :) = [cx, 5.5 + 2 * rand()];
        endif
      else                                      % static stones in the hole
        nSt = 1 + (gap > 17);                   % two stones in wide holes
        if level == 1 && rand() < 0.5
          nSt = 0;                              % small holes of level 1: jump directly
        endif
        stW = max(4.5, 8 - level);              % stones get narrower
        for k = 1:nSt
          stX = gx + gap * k / (nSt + 1);
          stY = 4 + 3 * rand();
          S(end+1, :) = [stX - stW / 2, stY, stX + stW / 2, stY + 1.2, 3];
          if rand() < 0.5
            cand(end+1, :) = [stX, stY + 3.4];  % risky book above a stone
          endif
        endfor
      endif
      x = gx + gap;
    else
      x = x + segLen;
    endif
  endfor
  nPick = min(5 + level, size(cand, 1));        % 6 books (level 1) to 10 books (level 5)
  idx   = randperm(size(cand, 1));              % random order of the candidates
  books = cand(idx(1:nPick), :);                % keep only nPick books
  if level >= 2 && size(cand, 1) > nPick
    coffee = cand(idx(nPick + 1), :);           % one coffee cup per level from level 2
  else
    coffee = zeros(0, 2);
  endif
  goalX       = x - 8;                          % flag position
  worldLength = x + 5;
endfunction

% ---- Function: rectangles [x1 y1 x2 y2] -> patch matrices (1 polygon per column)
function [X, Y] = rects_xy(R)
  X = [R(:,1), R(:,3), R(:,3), R(:,1)]';
  Y = [R(:,2), R(:,2), R(:,4), R(:,4)]';
endfunction

% ---- Function: shape of a virus (spiky ball, relative to its base) -----
function [sx, sy] = virus_shape(type, w, h)
  switch type
    case 1
      nSp = 10; inner = 0.60; scale = 0.50;     % green virus
    case 2
      nSp = 8;  inner = 0.45; scale = 0.58;     % red virus (long spikes)
    case 3
      nSp = 14; inner = 0.65; scale = 0.52;     % boss
    otherwise
      nSp = 6;  inner = 0.50; scale = 0.55;     % flying virus
  endswitch
  a = linspace(0, 2 * pi, 2 * nSp + 1);         % angles around the virus
  r = ones(1, 2 * nSp + 1);
  r(2:2:end) = inner;                           % alternate spike and base radius
  sx = scale * w * r .* cos(a);
  sy = scale * h * r .* sin(a) + h / 2;
endfunction

% ---- Function: a key is pressed ----------------------------------------
function key_press(fig, evt)
  key  = lower(evt.Key);                        % key name in lower case
  keys = getappdata(fig, 'keys');               % [left right] pressed state
  setappdata(fig, 'lastKey', key);              % last key (used by wait_for_key)
  switch key
    case {'left', 'leftarrow', 'q'}
      keys(1) = true;
    case {'right', 'rightarrow', 'd'}
      keys(2) = true;
    case {'up', 'uparrow', 'z', 'space', ' '}
      setappdata(fig, 'jumpRequested', true);   % jump asked
    case 'p'
      setappdata(fig, 'paused', ~getappdata(fig, 'paused'));  % pause on/off
  endswitch
  setappdata(fig, 'keys', keys);
endfunction

% ---- Function: a key is released ---------------------------------------
function key_release(fig, evt)
  key  = lower(evt.Key);
  keys = getappdata(fig, 'keys');
  switch key
    case {'left', 'leftarrow', 'q'}
      keys(1) = false;
    case {'right', 'rightarrow', 'd'}
      keys(2) = false;
  endswitch
  setappdata(fig, 'keys', keys);
endfunction

% ---- Function: wait for a key (any key if validKeys is empty) ----------
function key = wait_for_key(fig, validKeys)
  setappdata(fig, 'lastKey', '');               % forget old key presses
  key = '';
  while ishandle(fig)
    key = getappdata(fig, 'lastKey');
    if ~isempty(key) && (isempty(validKeys) || any(strcmp(key, validKeys)))
      return;
    endif
    drawnow();
    pause(0.05);
  endwhile
  key = '';                                     % figure closed
endfunction

% ---- Function: display a text screen (rules, results) ------------------
function show_screen(ax, message)
  set(get(ax, 'Parent'), 'Color', [0.05 0.05 0.2]);  % dark background
  cla(ax);
  axis(ax, [0 100 0 100]);
  axis(ax, 'off');
  text(ax, 50, 50, message, 'HorizontalAlignment', 'center', ...
       'Color', 'w', 'FontSize', 13);
  drawnow();
endfunction

