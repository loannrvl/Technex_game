%                   blocks, holes, floating stone platforms, moving platforms, spikes, books,
%                   coffee cup (invincibility), 4 virus types (green: stompable, red: not
%                   stompable, flying: not stompable, boss: 3 stomps), flag, clouds, hills
% VARIABLES       : px, py (player position), vy (vertical speed), lives, totalScore, level,
%                   S (solid rectangles), P (moving platforms), spikes, books, coffee,
